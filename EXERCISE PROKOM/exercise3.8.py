lokasi = ['Jepang', 'Cina', 'Swiss', 'Moroko']

print("original list:")
print(lokasi)
print("Alphabetical list:")
print(sorted(lokasi))
print("Original list is unchanged:")
print(lokasi)
print("Reverse alphabetical list:")
print(sorted(lokasi, reverse=True))
print("Original list is still unchanged:")
print(lokasi)
print("Reverse with reverse:")
lokasi.reverse()
print(lokasi)
print("Reverse with reverse again:")        
print(lokasi)   
print("Sort with sort:")
lokasi.sort()   
print(lokasi)
print("Sort with sort reverse:")
lokasi.sort(reverse=True)
print(lokasi)